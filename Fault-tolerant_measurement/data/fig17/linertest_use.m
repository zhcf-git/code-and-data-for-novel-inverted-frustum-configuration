
clc; clear; close all;

%% =======================
% 原始数据
% 列顺序：[Input, H6, H12, H18, H24]
%% =======================

Y_raw = [

1.020863986	1.003903065	0.950770242	0.903754415	0.909939329
1.958718787	1.921026381	1.852469399	1.82581698	1.844409678
2.966581187	2.909090393	2.811995479	2.832924478	2.85566471
3.975974331	3.906228047	3.786304177	3.826043614	3.870839085
4.937282907	4.855694349	4.712189362	4.786276782	4.861564995

];

% 将 NaN 替换成实际 H6、H12、H18 数据

%% =======================
% 零载荷补零
%% =======================

Y = [zeros(1, size(Y_raw,2)); Y_raw];

%% =======================
% 横轴：实际输入力
%% =======================

x = Y(:,1);

%% =======================
% 颜色定义
% 绘图顺序：24、18、12、6 Channels
%% =======================


%% =======================

cInput = [0.60 0.00 0.10];   % 深红色：Reference

colorSet = [
    0.00 0.35 0.60;   % 24 Channels 深蓝色
    0.72 0.42 0.10;   % 18 Channels 深橙色
    0.20 0.48 0.22;   % 12 Channels 深绿色
    0.41 0.28 0.55;   % 6 Channels  深紫色
];
%% =======================
% 绘图
%% =======================

figure('Color','w', ...
       'Position',[200 150 760 560]);

hold on;
grid on;
box on;

% Input：深红色实心三角形
plot(x, Y(:,1), '-^', ...
    'Color', cInput, ...
    'LineWidth', 1.8, ...
    'MarkerSize', 4, ...
    'MarkerFaceColor', cInput);

% 24、18、12、6 Channels：空心圆点
plot_columns = [5 4 3 2];

for i = 1:4
    plot(x, Y(:,plot_columns(i)), '-o', ...
        'Color', colorSet(i,:), ...
        'LineWidth', 1.8, ...
        'MarkerSize', 4, ...
        'MarkerFaceColor', 'none');
end

%% =======================
% 坐标轴与标题
%% =======================

xlabel('Reference Force (N)');
ylabel('Measured Force (N)');


%% =======================
% 图例
%% =======================

lgd = legend({'Input Fy', ...
        'Fault-Free Condition', ...
        'Condition 1', ...
        'Condition 2', ...
        'Condition 3'}, ...
        'Location','northwest');

lgd.Box = 'off';

%% =======================
